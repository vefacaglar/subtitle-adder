"""Generates src/pyunicode_tables.rs from the running CPython's Unicode database (run with the engine's
CPython 3.11, Unicode 14.0):  engine/.venv/Scripts/python.exe -I tools/gen_pyunicode.py > src/pyunicode_tables.rs
"""
import sys
import unicodedata

MAX = sys.maxunicode + 1


def ranges(pred):
    out, start = [], None
    for cp in range(MAX):
        ok = pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, MAX - 1))
    return out


def emit_ranges(name, rs):
    print(f"pub static {name}: &[(u32, u32)] = &[")
    for lo, hi in rs:
        print(f"    (0x{lo:X}, 0x{hi:X}),")
    print("];")


def rust_str(s):
    bs = chr(92)
    return "\"" + "".join(bs + "u{" + format(ord(c), "X") + "}" for c in s) + "\""


print(f"// @generated by tools/gen_pyunicode.py (CPython {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}).")
print("// Do not edit by hand.")
print()
emit_ranges("ALNUM", ranges(str.isalnum))
emit_ranges("ALNUM_NOT_DECIMAL", ranges(lambda c: c.isalnum() and not c.isdecimal()))
emit_ranges("DIGIT", ranges(str.isdigit))
emit_ranges("UPPER", ranges(str.isupper))
emit_ranges("LOWER", ranges(str.islower))

# Decimal digit runs: (lo, hi, value of lo); values increase by one along a run.
dec = []
for cp in range(MAX):
    c = chr(cp)
    if c.isdecimal():
        v = unicodedata.decimal(c)
        if dec and dec[-1][1] == cp - 1 and dec[-1][2] + (cp - dec[-1][0]) == v:
            dec[-1] = (dec[-1][0], cp, dec[-1][2])
        else:
            dec.append((cp, cp, v))
print("pub static DECIMAL: &[(u32, u32, u32)] = &[")
for lo, hi, v in dec:
    print(f"    (0x{lo:X}, 0x{hi:X}, {v}),")
print("];")

print("pub static LOWER_MAP: &[(u32, &str)] = &[")
for cp in range(MAX):
    c = chr(cp)
    if 0xD800 <= cp <= 0xDFFF:
        continue
    if c.lower() != c:
        print(f"    (0x{cp:X}, {rust_str(c.lower())}),")
print("];")
print("pub static CASEFOLD_MAP: &[(u32, &str)] = &[")
for cp in range(MAX):
    c = chr(cp)
    if 0xD800 <= cp <= 0xDFFF:
        continue
    if c.casefold() != c:
        print(f"    (0x{cp:X}, {rust_str(c.casefold())}),")
print("];")
