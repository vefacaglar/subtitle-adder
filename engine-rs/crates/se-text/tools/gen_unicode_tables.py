"""Generates src/unicode_tables.rs: code point ranges where CPython's single-character str predicates
(isalpha, isalnum, isupper, islower) are true. Run with the reference Python (3.11, Unicode 14.0):

    engine/.venv/Scripts/python.exe -I engine-rs/crates/se-text/tools/gen_unicode_tables.py
"""
import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src" / "unicode_tables.rs"


def ranges(pred):
    out, start = [], None
    for cp in range(sys.maxunicode + 1):
        ok = pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, sys.maxunicode))
    return out


def table(name, pred):
    rs = ranges(pred)
    body = "".join(
        ("\n    " if i % 6 == 0 else " ") + f"(0x{a:X}, 0x{b:X})," for i, (a, b) in enumerate(rs)
    )
    return f"pub(crate) static {name}: [(u32, u32); {len(rs)}] = [{body}\n];\n"


parts = [
    "// @generated by tools/gen_unicode_tables.py from CPython "
    f"{sys.version.split()[0]} (Unicode {unicodedata.unidata_version}). Do not edit.\n"
    "// Inclusive code point ranges where the single-character str predicate is true.\n",
    table("ALPHA", str.isalpha),
    table("ALNUM", str.isalnum),
    table("UPPER", str.isupper),
    table("LOWER", str.islower),
]
OUT.write_text("\n".join(parts), encoding="utf-8", newline="\n")
print(OUT)
